#!/usr/bin/env python3
"""Offline TSV -> compiled reference coefficients; Python standard library only.

Run from any directory. Runtime/builds need neither Python nor the source TSV.
The schema deliberately preserves reference units: no sensor/working-space
calibration, DN scaling or physical validation is implied.
"""
import argparse
import csv
import hashlib
import io
import json
import math
from pathlib import Path


SCHEMA = 1


def generate(source):
    raw = source.read_bytes()
    reader = csv.DictReader(io.StringIO(raw.decode("utf-8-sig")), delimiter="\t")
    required = {"make", "model", "mode", "aliases", "noise_profile_table_count",
                "noise_profile_tables_json"}
    if not required.issubset(reader.fieldnames or []):
        raise ValueError("missing required TSV columns")
    profiles, samples = [], []
    row_count = 0
    for row in reader:
        row_count += 1
        tables = json.loads(row["noise_profile_tables_json"])
        if len(tables) != int(row["noise_profile_table_count"]):
            raise ValueError("noise table count mismatch at row %d" % row_count)
        if not tables:
            continue
        if not row["make"].strip() or not row["model"].strip():
            raise ValueError("empty camera identity")
        by_iso = {}
        for table in tables:
            values = [float(v) for v in table["curve_param_values"]]
            # Parse/verify both JSON representations, rather than silently
            # accepting inconsistent evidence from the export.
            attrs = table["attributes"]
            if values != [float(v) for v in attrs["curve_param"].split()]:
                raise ValueError("inconsistent curve_param")
            if len(values) not in (2, 6) or any(
                    not math.isfinite(v) or v < 0 for v in values):
                raise ValueError("invalid A/B coefficients")
            if len(values) == 2:
                values *= 3
            iso_values = [float(v) for v in table["iso_list_values"]]
            if not iso_values or iso_values != [float(v) for v in attrs["iso_list"].split()]:
                raise ValueError("inconsistent or empty ISO list")
            for iso in iso_values:
                if not math.isfinite(iso) or iso <= 0 or iso in by_iso:
                    raise ValueError("invalid or duplicate ISO within profile")
                by_iso[iso] = (iso, values[0::2], values[1::2])
        offset = len(samples)
        samples.extend(by_iso[iso] for iso in sorted(by_iso))
        profiles.append((row, offset, len(by_iso)))

    def number(value):
        return format(value, ".17g")

    def array(values):
        return "{" + ",".join(number(v) for v in values) + "}"

    def string(value):
        # ASCII escaped C++ literals, no input paths or timestamps in output.
        return json.dumps(value, ensure_ascii=True)

    digest = hashlib.sha256(raw).hexdigest()
    lines = ["// Generated by tools/gen_camera_noise_profiles.py; do not edit.",
             "// Reference coefficients only, not physically validated calibration.",
             "// schema=%d input_sha256=%s" % (SCHEMA, digest),
             "// rows=%d profiles=%d samples=%d generic=%d" % (
                 row_count, len(profiles), len(samples),
                 sum(not row["mode"].strip() for row, _, _ in profiles)),
             "static const CameraNoiseSample kCameraNoiseSamples[] = {"]
    for iso, a, b in samples:
        lines.append("{%s,%s,%s}," % (number(iso), array(a), array(b)))
    lines += ["};", "static const CameraNoiseProfileRecord kCameraNoiseProfiles[] = {"]
    for row, offset, count in profiles:
        lines.append("{%s,%s,%s,%s,%s,kCameraNoiseSamples+%d,%d}," % (
            string(row["make"]), string(row["model"]), string(row["aliases"]),
            string(row["mode"]), "false" if row["mode"].strip() else "true",
            offset, count))
    lines += ["};", "static const CameraNoiseDataInfo kCameraNoiseDataInfo = {",
              '    %d, "%s", %d, %d, %d' % (
                  SCHEMA, digest, row_count, len(profiles), len(samples)), "};", ""]
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[3]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=root / "camera_model.tsv")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] /
                        "rtengine/camera_noise_profiles.inc")
    parser.add_argument("--check", action="store_true",
                        help="verify existing output byte-for-byte without writing")
    args = parser.parse_args()
    output = generate(args.input).encode("utf-8")
    if args.check:
        if args.output.read_bytes() != output:
            raise SystemExit("generated camera noise profiles are out of date")
    else:
        args.output.write_bytes(output)
    print("\n".join(output.decode("utf-8").splitlines()[2:4]))


if __name__ == "__main__":
    main()
